/* ══════════════════════════════════════════════════════════════════════
   Hyperpax error types

   Single source of truth for the shape of every user-facing error in
   the app. The classifier (`./classify.ts`) takes any thrown thing
   and returns one of these. The UI layer (`@/widgets/errors/*`) is
   the ONLY thing that ever renders `UserFacingError` — raw
   `Error.message` strings are never shown to users.
   ══════════════════════════════════════════════════════════════════════ */

/** Severity drives both visual treatment and Sentry capture level. */
export type ErrorSeverity = "info" | "warning" | "error" | "fatal";

/**
 * Stable, app-wide identifiers for known error classes. Use the most
 * specific code that matches; fall back to `UNKNOWN` only when nothing
 * else fits — those are the ones we most want users to report.
 */
export type ErrorCode =
  // ── Wallet / signing ────────────────────────────────────────────────
  | "WALLET_NOT_CONNECTED"
  | "WALLET_USER_REJECTED"
  | "WALLET_WRONG_NETWORK"
  | "WALLET_INSUFFICIENT_FUNDS"
  | "WALLET_PROVIDER_UNAVAILABLE"
  | "WALLET_TIMEOUT"
  // ── On-chain / RPC ──────────────────────────────────────────────────
  | "RPC_DISCONNECTED"
  | "RPC_RATE_LIMITED"
  | "RPC_REVERT"
  | "RPC_GAS_ESTIMATION_FAILED"
  | "RPC_NONCE_TOO_LOW"
  | "RPC_REPLACEMENT_UNDERPRICED"
  | "RPC_TX_TIMEOUT"
  // ── HTTP / API ──────────────────────────────────────────────────────
  | "API_OFFLINE"
  | "API_TIMEOUT"
  | "API_RATE_LIMITED"
  | "API_UNAUTHORIZED"
  | "API_FORBIDDEN"
  | "API_NOT_FOUND"
  | "API_BAD_REQUEST"
  | "API_SERVER_ERROR"
  | "API_BAD_GATEWAY"
  | "API_PAYLOAD_INVALID"
  // ── Live data / WebSocket ───────────────────────────────────────────
  | "WS_CONNECT_FAILED"
  | "WS_DISCONNECTED"
  | "WS_STALE"
  // ── Form / validation ───────────────────────────────────────────────
  | "VALIDATION_AMOUNT_INVALID"
  | "VALIDATION_INSUFFICIENT_BALANCE"
  | "VALIDATION_BELOW_MIN"
  | "VALIDATION_ABOVE_MAX"
  | "VALIDATION_PRECISION"
  | "VALIDATION_REQUIRED_FIELD"
  // ── Trade / position lifecycle ──────────────────────────────────────
  | "TRADE_SLIPPAGE_EXCEEDED"
  | "TRADE_MARKET_HALTED"
  | "TRADE_INSUFFICIENT_LIQUIDITY"
  | "TRADE_POSITION_LIQUIDATABLE"
  | "TRADE_TP_SL_INVALID"
  // ── App / runtime ───────────────────────────────────────────────────
  | "RUNTIME_ABORTED"
  | "RUNTIME_HYDRATION"
  | "RUNTIME_CHUNK_LOAD"
  | "RUNTIME_PERMISSION_DENIED"
  | "RUNTIME_QUOTA_EXCEEDED"
  // ── Catch-all ───────────────────────────────────────────────────────
  | "UNKNOWN";

/**
 * Free-form context tag used to scope a thrown error. Whatever string
 * you pass reaches Sentry as a tag and helps triage. Examples:
 * `"order-form/place-order"`, `"deposit/approve"`, `"chart/load"`.
 */
export type ErrorContext = string;

/** Normalised, user-safe view of any thrown thing. Never holds raw stack traces. */
export interface UserFacingError {
  /** Stable app-wide identifier — see `ErrorCode`. */
  code: ErrorCode;
  /** Short, friendly headline. ~3–6 words. Sentence case. No tech jargon. */
  title: string;
  /** One-line plain-English description of what happened. */
  message: string;
  /**
   * Optional actionable suggestion the user can take RIGHT NOW. If a
   * fix is possible, this is non-null. Examples:
   * "Reconnect your wallet", "Top up your account", "Try again".
   */
  suggestedFix: string | null;
  /** Severity drives the visual treatment and Sentry level. */
  severity: ErrorSeverity;
  /**
   * Whether this error is worth reporting to Sentry. False for
   * benign / expected errors (e.g. user rejected a signature) so we
   * don't pollute the dashboard with noise.
   */
  isReportable: boolean;
  /**
   * Whether the failed operation can be safely retried by the user.
   * Drives the "Retry" affordance in toasts and panels.
   */
  isRetryable: boolean;
  /** Free-form context describing where the error came from. */
  context?: ErrorContext;
  /**
   * The original thrown value, kept around so the report flow can
   * forward it to Sentry. Never rendered to the user.
   */
  cause?: unknown;
  /**
   * Opaque per-error fingerprint used to dedupe in Sentry.
   * Generated by the classifier; consumers should treat as read-only.
   */
  fingerprint?: string[];
}

/** Options accepted by the `reportError(err, opts)` helper. */
export interface ReportErrorOptions {
  context?: ErrorContext;
  /** User-supplied feedback paired with the error in Sentry. */
  feedback?: {
    name?: string;
    email?: string;
    comments: string;
  };
  /** Extra structured data attached to the Sentry event. */
  extra?: Record<string, unknown>;
  /** Tags merged into the Sentry event scope. */
  tags?: Record<string, string>;
}

/** Options accepted by `useErrorHandler().handle(err, opts)`. */
export interface HandleErrorOptions extends ReportErrorOptions {
  /**
   * If false, the toast is suppressed (caller wants to render its own
   * inline UI). `reportError` is still invoked when `isReportable`.
   */
  showToast?: boolean;
  /**
   * Optional retry callback wired to the toast's "Retry" action button.
   * Only shown when the classified error has `isRetryable === true`.
   */
  onRetry?: () => void | Promise<void>;
  /**
   * Optional caller-supplied title override (e.g. "Failed to add size").
   * The catalog's user-friendly `message` and `suggestedFix` are still
   * shown — this only replaces the headline so callers can keep their
   * domain copy. Defaults to the catalog's `title`.
   */
  titleOverride?: string;
}
