/* ══════════════════════════════════════════════════════════════════════
   Native PAX <-> WPAX9 helpers.

   The PECOR matching engine only speaks ERC-20, but the user's wallet
   may hold either native PAX (gas coin), wrapped WPAX9 (ERC-20), or
   both. For the "PAX/USD" market we present a unified PAX balance in
   the UI and silently wrap on the user's behalf whenever a sell trade
   needs more WPAX9 than the user holds.

   Buys are simpler — `marketBuy` always delivers WPAX9. Combined with
   the unified balance display, the user perceives "I bought PAX" with
   no exposure to the wrapper concept. They can unwrap manually via a
   separate affordance if they ever need native gas top-up.

   This module is split into:
     · `wpax9MinimalAbi`     — IWETH-style entry points (deposit/withdraw)
     · `computeWrapShortfall` — pure: how much native to wrap
     · `computeUnwrapAmount`  — pure: how much WPAX9 to unwrap

   The hooks layer wires these into actual writeContract calls.
   ══════════════════════════════════════════════════════════════════════ */

