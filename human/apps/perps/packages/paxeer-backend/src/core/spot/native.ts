/* ── pure math helpers ─────────────────────────────────────────── */

export interface WrapPlan {
  /** True when the user already has enough WPAX9 — no wrap needed. */
  sufficient: boolean;
  /** Amount of native PAX that must be wrapped, in 18-dec wei. */
  wrapAmount: bigint;
  /** Whether the combined native + WPAX9 balance can cover the trade. */
  feasible: boolean;
  /** Required WPAX9 amount the trade consumes. */
  required: bigint;
}

/**
 * Compute the wrap plan for a sell trade on the PAX market.
 *
 * @param required        WPAX9 amount the trade needs to spend.
 * @param wpaxBalance     User's current WPAX9 ERC-20 balance.
 * @param nativeBalance   User's current native PAX balance (wei).
 * @returns `WrapPlan` indicating whether a wrap is needed and how much.
 *
 * The plan is **infeasible** when `wpaxBalance + nativeBalance < required`.
 * The caller should surface a "Not enough PAX" error in that case.
 */
export function computeWrapShortfall(
  required: bigint,
  wpaxBalance: bigint,
  nativeBalance: bigint,
): WrapPlan {
  if (required <= 0n) {
    return { sufficient: true, wrapAmount: 0n, feasible: true, required };
  }
  if (wpaxBalance >= required) {
    return { sufficient: true, wrapAmount: 0n, feasible: true, required };
  }
  const shortfall = required - wpaxBalance;
  const feasible = nativeBalance >= shortfall;
  return {
    sufficient: false,
    wrapAmount: feasible ? shortfall : nativeBalance,
    feasible,
    required,
  };
}

export interface UnwrapPlan {
  /** Whether the user already has enough native PAX. */
  sufficient: boolean;
  /** Amount of WPAX9 that must be unwrapped. */
  unwrapAmount: bigint;
  /** Whether the combined balance can cover the requirement. */
  feasible: boolean;
}

/**
 * Compute the inverse: how much WPAX9 to unwrap to top up a native PAX
 * balance for things like gas reserves or `swapExactInToNative`-style
 * flows (not used by the spot order pipeline today but exposed for
 * future composability).
 */
export function computeUnwrapAmount(
  requiredNative: bigint,
  nativeBalance: bigint,
  wpaxBalance: bigint,
): UnwrapPlan {
  if (requiredNative <= 0n) {
    return { sufficient: true, unwrapAmount: 0n, feasible: true };
  }
  if (nativeBalance >= requiredNative) {
    return { sufficient: true, unwrapAmount: 0n, feasible: true };
  }
  const shortfall = requiredNative - nativeBalance;
  const feasible = wpaxBalance >= shortfall;
  return {
    sufficient: false,
    unwrapAmount: feasible ? shortfall : wpaxBalance,
    feasible,
  };
}

/**
 * Helper: should the PAX-market sell pipeline wrap before trading?
 * Wraps the result of `computeWrapShortfall` in a one-line boolean
 * predicate for hook ergonomics.
 */
export function shouldWrapBeforeSell(plan: WrapPlan): boolean {
  return plan.feasible && !plan.sufficient && plan.wrapAmount > 0n;
}
