#!/usr/bin/env python3
"""Generate the Paxeer X Network system reference under docs/system/ from source."""
import ast
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
HEADER = "<!-- Generated by tools/docs/gen-system-docs.sh. Do not edit by hand. -->\n\n"


def rel(path):
    return path.relative_to(ROOT).as_posix()


def read(path):
    return path.read_text(encoding="utf-8")


def cell(value):
    return str(value).replace("|", "\\|").replace("\n", " ")


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(cell(v) for v in row) + " |" for row in rows]
    return "\n".join(out) + "\n"


def go_sources(directory):
    return sorted(p for p in directory.glob("*.go") if not p.name.endswith("_test.go"))


# Router routes -------------------------------------------------------------

def gen_routes():
    path = ROOT / "tools/paxeer-x/route-catalogue.json"
    cat = json.loads(read(path))
    out = [HEADER, "# Router routes\n\n",
           f"Source: `{rel(path)}` (schema `{cat['schema']}`), the catalogue of the hosted gateway route table.\n\n",
           f"- Chain id: `{cat['chain_id']}`\n- Canonical origin: `{cat['canonical_origin']}`\n",
           f"- Services: {len(cat['services'])}\n- Routes: {len(cat['routes'])}\n\n",
           "## Services\n\n"]
    services = sorted(cat["services"], key=lambda s: s["id"])
    out.append(table(["Service", "Purpose", "Exposure", "Discovery path", "Authentication"],
                     [[s["id"], s.get("purpose", ""), s.get("exposure", ""), s.get("discovery_path", ""),
                       s.get("authentication", "")] for s in services]))
    out.append("\n## Routes by service\n")
    by_service = {}
    for r in cat["routes"]:
        by_service.setdefault(r["service"], []).append(r)
    for name in sorted(by_service):
        routes = sorted(by_service[name], key=lambda r: (r["path"], r["method"]))
        out.append(f"\n### {name}\n\n")
        out.append(table(["Method", "Path", "Transport", "Authentication", "Timeout (s)", "Retries", "Consumers"],
                         [[r["method"], f"`{r['path']}`", r.get("transport", ""), r.get("authentication", ""),
                           r.get("timeout_seconds", ""), r.get("retries", ""),
                           ", ".join(r.get("consumers", []))] for r in routes]))
    out.append("\n## Denied surfaces\n\n")
    out += [f"- `{d}`\n" for d in sorted(cat.get("denied_surfaces", []))]
    return "routes.md", "".join(out)


# EVM JSON-RPC --------------------------------------------------------------

CTOR = re.compile(r"func (New\w+)\((?:[^()]|\((?:[^()]|\([^()]*\))*\))*\)\s*\(?\*?(\w+)[^{\n]*\{")
METHOD = re.compile(r"^func \(\w+ \*?(\w+)\) ([A-Z]\w*)\((.*?)\)\s*(.*?)\s*\{\s*$", re.M)
STRUCT = re.compile(r"^type (\w+) struct \{\n(.*?)^\}", re.M | re.S)


def gen_rpc():
    rpc = ROOT / "rpc"
    ctors, methods, embeds = {}, {}, {}
    for src in go_sources(rpc):
        text = read(src)
        for name, typ in CTOR.findall(text):
            ctors[name] = typ
        for typ, name, params, result in METHOD.findall(text):
            methods.setdefault(typ, {})[name] = (params, result, rel(src))
        for typ, body in STRUCT.findall(text):
            embeds[typ] = re.findall(r"^\t\*?([A-Z]\w*)\s*$", body, re.M)
    server = read(rpc / "server.go")
    variables = dict(re.findall(r"(\w+)(?:, \w+)? :?= (New\w+)\(", server))

    def resolve(expr):
        if expr.startswith("&"):
            return expr[1:]
        if expr.startswith("New"):
            return ctors.get(expr)
        return ctors.get(variables.get(expr, ""))

    def all_methods(typ, seen=()):
        found = {}
        for parent in embeds.get(typ, []):
            if parent not in seen:
                found.update(all_methods(parent, seen + (typ,)))
        found.update(methods.get(typ, {}))
        return found

    registered = {}
    for ns, expr in re.findall(r'Namespace:\s*"(\w+)",\s*Service:\s*(&?\w+)', server):
        typ = resolve(expr)
        if not typ:
            raise SystemExit(f"rpc: cannot resolve service {expr}")
        for name, (params, result, src) in all_methods(typ).items():
            method = f"{ns}_{name[0].lower()}{name[1:]}"
            kind = "subscription" if "rpc.Subscription" in result else "call"
            registered.setdefault(method, (typ, kind, src))
    out = [HEADER, "# EVM JSON-RPC methods\n\n",
           "Source: the `rpc.API` registrations in `rpc/server.go` (HTTP and WebSocket) and the exported methods of each "
           "registered service type, named `<namespace>_<method>` as the JSON-RPC server derives them. "
           "The `test` namespace is only served on non-live chain ids; operators can deny methods by configuration.\n\n",
           f"Total methods: {len(registered)}\n"]
    by_ns = {}
    for m, v in registered.items():
        by_ns.setdefault(m.split("_", 1)[0], []).append((m, v))
    for ns in sorted(by_ns):
        out.append(f"\n## {ns}\n\n")
        out.append(table(["Method", "Kind", "Service type", "Source"],
                         [[f"`{m}`", k, t, f"`{s}`"] for m, (t, k, s) in sorted(by_ns[ns])]))
    return "rpc.md", "".join(out)


# Precompiles ---------------------------------------------------------------

def abi_signature(entry):
    def types(items):
        return ", ".join((f"{i['type']} {i.get('name', '')}").strip() for i in items or [])
    sig = f"{entry.get('name', entry['type'])}({types(entry.get('inputs'))})"
    if entry.get("outputs"):
        sig += f" returns ({types(entry['outputs'])})"
    return sig


def gen_precompiles():
    out = [HEADER, "# Precompile ABIs\n\n",
           "Source: `precompiles/<name>/abi.json`, the address constants in `precompiles/<name>/*.go` and the "
           "Solidity interfaces in `contracts/src/precompiles/`.\n"]
    addr_re = re.compile(r'(\w*Address)\s*=\s*"(0x[0-9a-fA-F]{40})"')
    rows = []
    sections = []
    for abi_path in sorted((ROOT / "precompiles").glob("*/*abi*.json")):
        pkg = abi_path.parent
        addresses = sorted({a for src in go_sources(pkg) for _, a in addr_re.findall(read(src))})
        entries = json.loads(read(abi_path))
        rows.append([pkg.name, f"`{rel(abi_path)}`", ", ".join(f"`{a}`" for a in addresses) or "-",
                     sum(1 for e in entries if e.get("type") == "function")])
        sec = [f"\n## {pkg.name} (`{abi_path.name}`)\n\n"]
        if addresses:
            sec.append("Address: " + ", ".join(f"`{a}`" for a in addresses) + "\n\n")
        for kind in ("function", "event", "error"):
            items = sorted((e for e in entries if e.get("type") == kind), key=abi_signature)
            if not items:
                continue
            sec.append(f"### {kind.capitalize()}s\n\n")
            for e in items:
                mut = f" `{e['stateMutability']}`" if kind == "function" and e.get("stateMutability") else ""
                sec.append(f"- `{abi_signature(e)}`{mut}\n")
            sec.append("\n")
        sections.append("".join(sec))
    out.append("\n## Summary\n\n")
    out.append(table(["Precompile", "ABI", "Address", "Functions"], rows))
    out += sections
    out.append("\n## Solidity interfaces (`contracts/src/precompiles/`)\n")
    fn_re = re.compile(r"function\s+(\w+)\s*\(([^)]*)\)([^;{]*)[;{]", re.S)
    for sol in sorted((ROOT / "contracts/src/precompiles").glob("*.sol")):
        text = re.sub(r"//[^\n]*|/\*.*?\*/", "", read(sol), flags=re.S)
        out.append(f"\n### {sol.stem}\n\n")
        for name, params, tail in fn_re.findall(text):
            p = " ".join(params.split())
            t = " ".join(tail.split())
            out.append(f"- `{name}({p}){(' ' + t) if t else ''}`\n")
        for const, addr in re.findall(r"constant\s+(\w+)\s*=\s*(0x[0-9a-fA-F]{40})", text):
            out.append(f"- constant `{const}` = `{addr}`\n")
    return "precompiles.md", "".join(out)


# Chain modules -------------------------------------------------------------

def struct_fields(body):
    fields = []
    for line in body.splitlines():
        m = re.match(r"^\t([A-Z]\w*)\s+(\S+)\s*(`.*`)?", line)
        if not m or m.group(1).startswith("XXX_"):
            continue
        tag = m.group(3) or ""
        j = re.search(r'json:"([^",]+)', tag)
        fields.append((j.group(1) if j else m.group(1), m.group(2)))
    return fields


def gen_chain_modules():
    out = [HEADER, "# Chain modules and parameters\n\n",
           "Source: `modules/<name>/types/*.go`: the `Params` struct, `Msg*` message types and proposal type constants.\n"]
    rows = []
    sections = []
    for mod in sorted(p for p in (ROOT / "modules").iterdir() if p.is_dir()):
        types_dir = mod / "types"
        srcs = go_sources(types_dir) if types_dir.is_dir() else []
        params, msgs, props = [], set(), set()
        for src in srcs:
            text = read(src)
            for name, body in STRUCT.findall(text):
                if name == "Params" and not params:
                    params = struct_fields(body)
                if name.startswith("Msg") and not name.endswith("Response") and name != "Msg":
                    msgs.add(name)
            props.update(re.findall(r'ProposalType\w*\s*=\s*"(\w+)"', text))
        rows.append([mod.name, len(params), len(msgs), ", ".join(sorted(props)) or "-"])
        sec = [f"\n## {mod.name}\n\n"]
        if params:
            sec.append("### Parameters\n\n" + table(["Field", "Go type"], [[f"`{n}`", f"`{t}`"] for n, t in params]) + "\n")
        if msgs:
            sec.append("### Messages\n\n" + "".join(f"- `{m}`\n" for m in sorted(msgs)) + "\n")
        if props:
            sec.append("### Proposal types\n\n" + "".join(f"- `{p}`\n" for p in sorted(props)) + "\n")
        if len(sec) == 1:
            sec.append("No parameters, messages or proposal types declared in `types/`.\n")
        sections.append("".join(sec))
    out.append("\n## Summary\n\n" + table(["Module", "Params", "Messages", "Proposal types"], rows))
    return "chain-modules.md", "".join(out + sections)


# Kernel modules ------------------------------------------------------------

def c_enum_values():
    values = {}
    for header in (ROOT / "include/layerx").glob("*.h"):
        text = read(header)
        for name, value in re.findall(r"\b((?:LX|LXP)_[A-Z0-9_]+)\s*=\s*([^,\n}]+)", text):
            values.setdefault(name, value.strip())
        for name, value in re.findall(r"^#define ((?:LX|LXP)_[A-Z0-9_]+)[ \t]+([^\n]+)", text, re.M):
            values.setdefault(name, value.strip())
    return values


def gen_kernel_modules():
    values = c_enum_values()
    iface = re.compile(r"(LXP_MODULE_[A-Z]+),\s*(\w+),\s*\"(\w+)\",\s*(\w+)", re.S)
    out = [HEADER, "# LayerX kernel modules\n\n",
           "Source: the module ids in `include/layerx/lxp_module.h` and each `lxp_module_iface` registration "
           "with its `activity_types` table under `src/modules/`.\n"]
    mods = []
    for src in sorted((ROOT / "src/modules").rglob("*.c")):
        text = read(src)
        for mid, abi, name, table_name in iface.findall(text):
            arr = re.search(r"\b" + re.escape(table_name) + r"\[\]\s*=\s*\{(.*?)\}", text, re.S)
            acts = re.findall(r"\b(LX\w+)\b", arr.group(1)) if arr else []
            mods.append((values.get(mid, "?"), name, mid, values.get(abi, abi.rstrip("Uu")), rel(src), acts))
    mods.sort(key=lambda m: (int(m[0]) if m[0].isdigit() else 999, m[1]))
    out.append("\n## Summary\n\n" + table(["Id", "Module", "ABI version", "Activity types", "Registration"],
                                          [[i, n, a, len(acts), f"`{s}`"] for i, n, _, a, s, acts in mods]))
    for i, name, mid, abi, src, acts in mods:
        out.append(f"\n## {name} (`{mid}` = {i})\n\n")
        if acts:
            out.append(table(["Activity type", "Value"], [[f"`{a}`", f"`{values.get(a, '?')}`"] for a in acts]))
        else:
            out.append("No activity types registered.\n")
    return "kernel-modules.md", "".join(out)


# SDK surfaces --------------------------------------------------------------

TS_DECL = re.compile(r"^export\s+(?:declare\s+)?(?:default\s+)?(?:abstract\s+)?(?:async\s+)?"
                     r"(function\*?|class|const|let|interface|type|enum)\s+(\w+)", re.M)


def ts_exports(path, seen):
    if path in seen or not path.exists():
        return []
    seen.add(path)
    text = read(path)
    found = [(kind.rstrip("*"), name, rel(path)) for kind, name in TS_DECL.findall(text)]
    for names in re.findall(r"^export\s+(?:type\s+)?\{([^}]*)\}", text, re.M):
        for n in names.split(","):
            n = n.strip().split(" as ")[-1].strip()
            if n:
                found.append(("re-export", n, rel(path)))
    for spec in re.findall(r"^export \* from \"(\.[^\"]+)\"", text, re.M):
        target = (path.parent / spec).resolve()
        target = target.with_suffix(".ts") if target.suffix == ".js" else target
        found += ts_exports(target, seen)
    return found


def python_exports(init):
    tree = ast.parse(read(init))
    names = []
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "__all__" for t in node.targets):
            return sorted(ast.literal_eval(node.value))
        if isinstance(node, ast.ImportFrom):
            names += [a.asname or a.name for a in node.names]
        elif isinstance(node, (ast.FunctionDef, ast.ClassDef)) and not node.name.startswith("_"):
            names.append(node.name)
    return sorted(set(names))


def rust_exports(lib):
    items = re.findall(r"^pub\s+(mod|use|fn|struct|enum|trait|const|static|type)\s+([^;{(<\s]+(?:::\{[^}]*\})?)",
                       read(lib), re.M)
    macros = re.findall(r"^macro_rules!\s+(\w+)", read(lib), re.M)
    return sorted(set(items)) + [("macro", m) for m in sorted(macros)]


def gen_sdk():
    out = [HEADER, "# SDK surfaces\n\n",
           "Public API of the TypeScript, Python and Rust SDKs, read from their package entry points.\n"]
    ts = ROOT / "agent/sdk/typescript/src/index.ts"
    out.append(f"\n## TypeScript (`{rel(ts.parent.parent)}`)\n\nEntry point `{rel(ts)}`.\n\n")
    exports = sorted(set(ts_exports(ts, set())), key=lambda e: (e[2], e[1], e[0]))
    out.append(table(["Export", "Kind", "Defined in"], [[f"`{n}`", k, f"`{s}`"] for k, n, s in exports]))
    py = ROOT / "agent/sdk/python/layerx_sdk/__init__.py"
    out.append(f"\n## Python (`{rel(py.parent.parent)}`)\n\nPackage `layerx_sdk`, entry point `{rel(py)}`.\n\n")
    out += [f"- `{n}`\n" for n in python_exports(py)]
    rs = ROOT / "programs/sdk/rust/src/lib.rs"
    out.append(f"\n## Rust (`{rel(rs.parent.parent)}`)\n\nCrate root `{rel(rs)}`.\n\n")
    out.append(table(["Item", "Kind"], [[f"`{n}`", k] for k, n in rust_exports(rs)]))
    return "sdk.md", "".join(out)


# CLI -----------------------------------------------------------------------

def kebab(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "-", name).lower()


def gen_cli():
    cli = ROOT / "platform/cli/src"
    enums = {}
    variant_re = re.compile(r"((?:[ \t]*(?:///[^\n]*|#\[[^\n]*\])\n)*)[ \t]{4}([A-Z]\w*)\s*(\(([\w:]+)\)|\{|,)")
    for src in sorted(cli.rglob("*.rs")):
        text = read(src)
        for m in re.finditer(r"#\[derive\([^)]*\bSubcommand\b[^)]*\)\]\s*(?:#\[[^\n]*\]\s*)*(?:pub(?:\([^)]*\))?\s+)?enum (\w+) \{\n(.*?)^\}",
                             text, re.S | re.M):
            body = m.group(2)
            body = re.sub(r"^[ \t]{8,}[^\n]*\n", "", body, flags=re.M)
            variants = []
            for attrs, name, _, inner, _ in [(v.group(1), v.group(2), v.group(3), v.group(4), None)
                                            for v in variant_re.finditer(body)]:
                doc = " ".join(l.strip()[3:].strip() for l in attrs.splitlines() if l.strip().startswith("///"))
                renamed = re.search(r'#\[command\([^\]]*name\s*=\s*"([^"]+)"', attrs)
                variants.append((renamed.group(1) if renamed else kebab(name), doc, (inner or "").split("::")[-1]))
            enums[m.group(1)] = (variants, rel(src))
    main = read(cli / "main.rs")
    bin_name = re.search(r'#\[command\(name = "([^"]+)"', main).group(1)
    out = [HEADER, "# CLI commands\n\n",
           f"Source: the clap `Subcommand` definitions in `{rel(cli)}`. Binary name `{bin_name}`; "
           f"run `{bin_name} <command> --help` for flags.\n\n"]

    def walk(enum, prefix, depth, seen):
        variants, _ = enums[enum]
        for name, doc, inner in variants:
            cmd = f"{prefix} {name}"
            out.append(f"{'  ' * depth}- `{cmd}`" + (f": {doc}" if doc else "") + "\n")
            if inner in enums and inner not in seen:
                walk(inner, cmd, depth + 1, seen | {inner})

    walk("Command", bin_name, 0, {"Command"})
    return "cli.md", "".join(out)


# Governance ----------------------------------------------------------------

def gen_governance():
    out = [HEADER, "# Governance proposal types\n\n",
           "Source: `ProposalType*` constants in `modules/` and `sdk/x/` (Go), and the kernel governance "
           "module activity types.\n\n"]
    rows = []
    for base in ("modules", "sdk/x"):
        for src in sorted((ROOT / base).rglob("*.go")):
            if src.name.endswith("_test.go") or "testutil" in src.parts:
                continue
            for const, value in re.findall(r"\b(ProposalType\w*)\s*=\s*\"(\w+)\"", read(src)):
                rows.append([f"`{value}`", f"`{const}`", f"`{rel(src)}`"])
    out.append("## Chain proposal types\n\n" + table(["Type", "Constant", "Source"], sorted(rows)))
    values = c_enum_values()
    gov = ROOT / "include/layerx/lxp_governance.h"
    if gov.exists():
        acts = sorted({n for n in re.findall(r"\b(LXP?_GOV\w*)\s*=", read(gov))})
        out.append(f"\n## Kernel governance (`{rel(gov)}`)\n\n")
        out.append(table(["Constant", "Value"], [[f"`{a}`", f"`{values.get(a, '?')}`"] for a in acts]))
    return "governance.md", "".join(out)


TITLES = {
    "routes.md": "Router routes",
    "rpc.md": "EVM JSON-RPC methods",
    "precompiles.md": "Precompile ABIs",
    "chain-modules.md": "Chain modules and parameters",
    "kernel-modules.md": "LayerX kernel modules",
    "sdk.md": "SDK surfaces",
    "cli.md": "CLI commands",
    "governance.md": "Governance proposal types",
}


def main():
    if len(sys.argv) != 2:
        raise SystemExit("usage: gen_system_docs.py <output-dir>")
    dest = Path(sys.argv[1])
    dest.mkdir(parents=True, exist_ok=True)
    docs = dict(g() for g in (gen_routes, gen_rpc, gen_precompiles, gen_chain_modules, gen_kernel_modules,
                              gen_sdk, gen_cli, gen_governance))
    index = [HEADER, "# Paxeer X Network system reference\n\n",
             "Generated from the repository sources. Regenerate with `tools/docs/gen-system-docs.sh`; "
             "`--check` fails when this directory is stale.\n\n"]
    index += [f"- [{TITLES[name]}]({name})\n" for name in TITLES]
    docs["INDEX.md"] = "".join(index)
    for name, text in docs.items():
        (dest / name).write_text(text.rstrip("\n") + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
