#!/usr/bin/env python3
"""Generate the SDK revert retriability tables from the error code registry.

usage: scripts/ci/result-codes-gen.py [--check]

Reads the Code and Retryable columns of section (b) of
spec/layerx-merge/contracts/address-table.md and rewrites, between the
generated-region markers, the LXP_RETRYABLE set of
agent/sdk/typescript/src/revert.ts (every code whose Retryable cell is yes)
and the LXP_RETRYABLE mapping of agent/sdk/python/layerx_sdk/revert.py
(every code with its Retryable cell as a bool), both in registry order.

With --check nothing is written; the exit status is 1 and each code whose SDK
entry differs from the Retryable column is named when either table drifts.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REGISTRY = ROOT / "spec/layerx-merge/contracts/address-table.md"
TYPESCRIPT = ROOT / "agent/sdk/typescript/src/revert.ts"
PYTHON = ROOT / "agent/sdk/python/layerx_sdk/revert.py"
CODE = re.compile(r"^LXP_[A-Z0-9]+(?:_[A-Z0-9]+)*$")
BEGIN = "BEGIN GENERATED by scripts/ci/result-codes-gen.py"
END = "END GENERATED"
TYPESCRIPT_ENTRY = re.compile(r'^  "(LXP_[A-Z0-9_]+)",$')
PYTHON_ENTRY = re.compile(r'^    "(LXP_[A-Z0-9_]+)": (True|False),$')


class GenerationError(Exception):
    pass


def registry_rows(text):
    _, marker, section = text.partition("\n## (b) ")
    if not marker:
        raise GenerationError(f"{REGISTRY.relative_to(ROOT)}: section (b) is missing")
    section = section.split("\n## ", 1)[0]
    rows = {}
    for line in section.splitlines():
        if not line.startswith("| LXP_"):
            continue
        cells = [cell.strip() for cell in line.split("|")]
        if len(cells) != 7 or cells[0] or cells[6]:
            raise GenerationError(f"registry row does not have five columns: {line}")
        code, retryable = cells[1], cells[5]
        if not CODE.match(code):
            raise GenerationError(f"{code}: not an LXP_ code name")
        if code in rows:
            raise GenerationError(f"{code}: more than one registry row")
        if retryable not in ("yes", "no"):
            raise GenerationError(
                f"{code}: Retryable cell {retryable!r} is neither yes nor no"
            )
        rows[code] = retryable == "yes"
    if not rows:
        raise GenerationError(
            f"{REGISTRY.relative_to(ROOT)}: section (b) holds no LXP_ row"
        )
    return rows


def region(path, text):
    lines = text.split("\n")
    begins = [index for index, line in enumerate(lines) if line.strip().endswith(BEGIN)]
    ends = [index for index, line in enumerate(lines) if line.strip().endswith(END)]
    if len(begins) != 1 or len(ends) != 1 or begins[0] >= ends[0]:
        raise GenerationError(
            f"{path.relative_to(ROOT)}: expected one generated region between markers"
        )
    return lines, begins[0] + 1, ends[0]


def typescript_lines(rows):
    return [f'  "{code}",' for code, retryable in rows.items() if retryable]


def python_lines(rows):
    return [f'    "{code}": {retryable},' for code, retryable in rows.items()]


def current_entries(path, body, pattern):
    entries = {}
    for line in body:
        match = pattern.match(line)
        if not match:
            raise GenerationError(
                f"{path.relative_to(ROOT)}: unexpected line in generated region: {line}"
            )
        code = match.group(1)
        if code in entries:
            raise GenerationError(
                f"{path.relative_to(ROOT)}: {code} appears more than once"
            )
        entries[code] = match.group(2) == "True" if pattern.groups == 2 else True
    return entries


def differing_codes(rows, entries, retryable_only):
    expected = (
        {code: True for code, retryable in rows.items() if retryable}
        if retryable_only
        else rows
    )
    codes = set(expected) | set(entries)
    return [code for code in codes if expected.get(code) != entries.get(code)]


def main(argv):
    if argv not in ([], ["--check"]):
        print("usage: scripts/ci/result-codes-gen.py [--check]", file=sys.stderr)
        return 2
    check = argv == ["--check"]
    try:
        rows = registry_rows(REGISTRY.read_text(encoding="utf-8"))
        order = {code: index for index, code in enumerate(rows)}
        failures = []
        for path, generate, pattern, retryable_only in (
            (TYPESCRIPT, typescript_lines, TYPESCRIPT_ENTRY, True),
            (PYTHON, python_lines, PYTHON_ENTRY, False),
        ):
            text = path.read_text(encoding="utf-8")
            lines, start, stop = region(path, text)
            wanted = generate(rows)
            if lines[start:stop] == wanted:
                continue
            if not check:
                path.write_text(
                    "\n".join(lines[:start] + wanted + lines[stop:]), encoding="utf-8"
                )
                print(f"rewrote {path.relative_to(ROOT)}")
                continue
            try:
                entries = current_entries(path, lines[start:stop], pattern)
            except GenerationError as error:
                failures.append(str(error))
                continue
            codes = differing_codes(rows, entries, retryable_only)
            codes.sort(key=lambda code: (order.get(code, len(order)), code))
            for code in codes:
                failures.append(
                    f"{path.relative_to(ROOT)}: {code} differs from the registry Retryable column"
                )
            if not codes:
                failures.append(
                    f"{path.relative_to(ROOT)}: generated region is not in registry order or form"
                )
    except (GenerationError, OSError) as error:
        print(f"result-codes-gen: {error}", file=sys.stderr)
        return 1
    for failure in failures:
        print(f"result-codes-gen: {failure}", file=sys.stderr)
    if failures:
        print(
            "result-codes-gen: run scripts/ci/result-codes-gen.py to regenerate",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
